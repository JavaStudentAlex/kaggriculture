#!/usr/bin/env python3
"""Build the top-player benchmark: a private Kaggle dataset and N CPU notebooks (no GPU quota, no Colab units).

    python research/procedural_graph/benchmark/make_top_bench.py --out DIR \\
        --graph cedar_ridge=RUN/bundles/g_900a45ee4b3107a7 --graph tetsutani_demand=RUN/bundles/tetsutani_demand ...
    kaggle datasets create -p DIR/dataset          # a later round: kaggle datasets version -p DIR/dataset -m ...
    for k in 1 .. N; do kaggle kernels push -p DIR/kernels/$k; done

Each --graph is an arena bundle (a directory with main.py, e.g. from a run's bundles/). The dataset holds them
with arena.py, bundle_agent.py and top_bench.py in top_bench_payload.tar. Notebook k (1..N) also attaches the
daily top-game datasets of --day (kaggle/kaggriculture-episodes-<day>), installs kaggle-environments, and runs
top_bench.py for shard k-1: every graph takes the place of a top player against the other's recorded moves on
the game's seed (top_bench.py). Build it where the bundles are (cliproxyapi) and push from the machine that
holds the Kaggle credentials. top_bench_report.py reads the notebooks' results.
"""
from __future__ import annotations

import argparse
import json
import shutil
import tarfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
PG = HERE.parent
REPO = PG.parents[1]

LAUNCHER = '''"""Top-player benchmark, shard {shard} of {shards} (generated by research/procedural_graph/benchmark/make_top_bench.py)."""
import os, shutil, subprocess, sys, tarfile
from pathlib import Path

print('CPUs', os.cpu_count(), flush=True)
subprocess.run([sys.executable, '-m', 'pip', 'install', '-q', 'kaggle-environments==1.32.7'], check=True)
payload = Path('/tmp/payload')
tars = [p for p in sorted(Path('/kaggle/input').rglob('top_bench_payload.tar')) if p.is_file()]
if tars:
    with tarfile.open(tars[0]) as t:
        t.extractall(payload, filter='data')
else:   # Kaggle unpacked the tar: copy it somewhere writable (top_bench.py writes the replay bundles)
    shutil.copytree(next(Path('/kaggle/input').rglob('top_bench.py')).parent, payload)
root = next(payload.rglob('top_bench.py')).parent
code = subprocess.run([sys.executable, 'top_bench.py', '--shard', '{index}', '--shards', '{shards}', '--top', '{top}',
                       '--graphs', '{graphs}', '--workers', '{workers}', '--deadline', '{deadline}'], cwd=root).returncode
print('TOP_BENCH_EXIT=%d' % code, flush=True)
'''


def metadata(kernel_id, code_file, dataset_sources):
    return json.dumps({'id': kernel_id, 'title': kernel_id.split('/', 1)[1], 'code_file': code_file,
                       'language': 'python', 'kernel_type': 'script', 'is_private': 'true', 'enable_gpu': 'false',
                       'enable_tpu': 'false', 'enable_internet': 'true', 'dataset_sources': list(dataset_sources),
                       'competition_sources': [], 'kernel_sources': []}, indent=2) + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--out', required=True)
    ap.add_argument('--graph', action='append', required=True, metavar='NAME=BUNDLE_DIR')
    ap.add_argument('--day', action='append', required=True, help='a published day, e.g. 2026-09-26')
    ap.add_argument('--top', type=int, default=80, help='top games per day, by average rating')
    ap.add_argument('--user', default='sunshinethroughfog')
    ap.add_argument('--slug', default='kaggriculture-top-bench', help='the dataset; the notebooks are <slug>-<k>')
    ap.add_argument('--shards', type=int, default=5)
    ap.add_argument('--workers', type=int, default=4)
    ap.add_argument('--deadline-hours', type=float, default=10.5, help='stop starting games after this')
    args = ap.parse_args()
    out = Path(args.out)
    if out.exists():
        shutil.rmtree(out)
    payload = out / 'payload'
    (payload / 'bundles').mkdir(parents=True)
    names = []
    for spec in args.graph:
        name, source = spec.split('=', 1)
        shutil.copytree(source, payload / 'bundles' / name, ignore=shutil.ignore_patterns('__pycache__'))
        names.append(name)
    shutil.copy2(PG / 'arena' / 'arena.py', payload / 'arena.py')
    shutil.copy2(REPO / 'shinka' / 'evolution' / 'pool_upgrade_bundle_agent.py', payload / 'bundle_agent.py')
    shutil.copy2(HERE / 'top_bench.py', payload / 'top_bench.py')
    dataset = out / 'dataset'
    dataset.mkdir()
    with tarfile.open(dataset / 'top_bench_payload.tar', 'w') as tar:
        tar.add(payload, arcname='.')
    (dataset / 'dataset-metadata.json').write_text(json.dumps(
        {'title': args.slug, 'id': f'{args.user}/{args.slug}', 'licenses': [{'name': 'other'}]}, indent=2) + '\n')
    sources = [f'{args.user}/{args.slug}'] + [f'kaggle/kaggriculture-episodes-{day}' for day in args.day]
    for k in range(1, args.shards + 1):
        folder = out / 'kernels' / str(k)
        folder.mkdir(parents=True)
        (folder / 'top_bench_run.py').write_text(LAUNCHER.format(
            shard=k, shards=args.shards, index=k - 1, top=args.top, graphs=','.join(names), workers=args.workers,
            deadline=int(args.deadline_hours * 3600)))
        (folder / 'kernel-metadata.json').write_text(metadata(f'{args.user}/{args.slug}-{k}', 'top_bench_run.py',
                                                              sources))
    games = args.top * len(args.day) * 2 * len(names)
    print(json.dumps({'graphs': names, 'days': args.day, 'games': games, 'per_notebook': -(-games // args.shards),
                      'tar_bytes': (dataset / 'top_bench_payload.tar').stat().st_size, 'dataset': str(dataset)},
                     indent=1))


if __name__ == '__main__':
    main()
